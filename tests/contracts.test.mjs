import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, readFile, writeFile, mkdir } from 'node:fs/promises';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFileSync, spawnSync } from 'node:child_process';
import { tmpdir } from 'node:os';
import { validate, loadSchema, schemaNames } from '../scripts/schema.mjs';
import { evaluate, findingIdentity, eventIdentity } from '../scripts/policy.mjs';

const base = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const cli = resolve(base, 'scripts/supply-chain.mjs');
const run = (...args) => execFileSync(process.execPath, [cli, ...args], { cwd: base, encoding: 'utf8' });
const readJson = async file => JSON.parse(await readFile(resolve(base, file), 'utf8'));
const scratch = await mkdtemp(resolve(tmpdir(), 'supply-chain-contracts-'));
const AT = '2026-10-31T00:00:00.000Z';

test('every contract is loadable and the synthetic examples validate against it', async () => {
  for (const name of ['snapshot', 'diff-events', 'policy', 'policy-result']) assert.equal((await loadSchema(name)).title.length > 0, true, name);
  assert.deepEqual(schemaNames.slice(0, 4), ['snapshot', 'diff-events', 'policy', 'policy-result']);
  const snapshot = await readJson('contracts/examples/enriched-snapshot.json');
  assert.deepEqual(validate(await loadSchema('snapshot'), snapshot).errors, []);
  assert.deepEqual(validate(await loadSchema('policy'), await readJson('contracts/policy.default.json')).errors, []);
  assert.deepEqual(validate(await loadSchema('policy-result'), await readJson('contracts/examples/policy-result.json')).errors, []);
  assert.deepEqual(validate(await loadSchema('snapshot'), await readJson('examples/demo-snapshot.json')).errors, []);
});

test('real scan and diff output validate as v1; malformed and unsupported documents are rejected', async () => {
  const out = resolve(scratch, 'fixture-snapshot.json');
  run('scan', '--config', resolve(base, 'examples/portfolio.example.json'), '--out', out);
  const scanned = JSON.parse(await readFile(out, 'utf8'));
  assert.deepEqual(validate(await loadSchema('snapshot'), scanned).errors, []);
  const events = resolve(scratch, 'events.json');
  run('diff', '--previous', resolve(base, 'contracts/examples/enriched-snapshot.json'), '--current', out, '--out', events);
  assert.deepEqual(validate(await loadSchema('diff-events'), JSON.parse(await readFile(events, 'utf8'))).errors, []);
  assert.match(run('validate', '--schema', 'snapshot', '--file', out) || 'ok', /ok|/);
  const broken = { ...scanned, nodes: [{ id: 'x', kind: 'planet', label: 'x' }], findings: [{ id: 'f', projectId: 'p', type: 't', severity: 'high', title: 't', evidence: 'e' }] };
  const problems = validate(await loadSchema('snapshot'), broken).errors;
  assert.ok(problems.some(problem => problem.path === '/nodes/0/kind'));
  assert.ok(problems.some(problem => problem.path === '/findings/0/severity'));
  const future = resolve(scratch, 'future.json');
  await writeFile(future, JSON.stringify({ ...scanned, schemaVersion: 2 }));
  const refused = spawnSync(process.execPath, [cli, 'validate', '--schema', 'snapshot', '--file', future], { encoding: 'utf8' });
  assert.equal(refused.status, 1);
  assert.match(refused.stderr, /schemaVersion/);
  const evaluated = spawnSync(process.execPath, [cli, 'evaluate', '--snapshot', future, '--policy', resolve(base, 'contracts/policy.default.json'), '--out', '-'], { encoding: 'utf8' });
  assert.equal(evaluated.status, 1);
  assert.match(evaluated.stderr, /does not match its v1 contract/);
  const typoPolicy = resolve(scratch, 'typo-policy.json');
  await writeFile(typoPolicy, JSON.stringify({ schemaVersion: 1, id: 'typo', version: '1', rules: { 'osv-advisry': { enabled: false } } }));
  const typo = spawnSync(process.execPath, [cli, 'evaluate', '--snapshot', out, '--policy', typoPolicy, '--out', '-'], { encoding: 'utf8' });
  assert.equal(typo.status, 1, 'a misspelled rule cannot silently disable anything');
});

test('evaluation is deterministic and distinguishes every coverage state', async () => {
  const snapshot = await readJson('contracts/examples/enriched-snapshot.json');
  const policy = await readJson('contracts/policy.default.json');
  const first = evaluate(snapshot, policy, { now: AT }), second = evaluate(snapshot, policy, { now: AT });
  assert.deepEqual(first, second);
  assert.deepEqual(first, await readJson('contracts/examples/policy-result.json'), 'contracts/examples/policy-result.json is stale; regenerate it with: node scripts/supply-chain.mjs evaluate --snapshot contracts/examples/enriched-snapshot.json --policy contracts/policy.default.json --at 2026-10-31T00:00:00.000Z --out contracts/examples/policy-result.json');
  const state = name => first.checks.artifacts.find(record => record.name === name);
  assert.equal(state('vulnerable-lib').osv, 'checked-with-results');
  assert.equal(state('clean-lib').osv, 'checked-and-none');
  assert.equal(state('flaky-lib').osv, 'failed');
  assert.equal(state('legacy-helper').osv, 'unqueried');
  assert.equal(state('requests').osv, 'unsupported');
  assert.equal(first.freshness.state, 'fresh');
  const byRule = rule => first.findings.filter(finding => finding.ruleId === rule);
  const advisory = byRule('osv-advisory')[0];
  assert.equal(advisory.actionability, 'actionable');
  assert.equal(advisory.severity, 'HIGH');
  assert.equal(advisory.severitySource, 'osv');
  assert.equal(advisory.checkedAt, '2026-10-30T12:05:00.000Z');
  assert.deepEqual(advisory.fixedBoundaries, ['1.0.3']);
  assert.deepEqual(advisory.dependencyPath.map(step => step.label), ['Web App', 'vulnerable-lib@1.0.2']);
  assert.equal(byRule('osv-lookup-failed')[0].coverageState, 'failed');
  assert.equal(byRule('osv-lookup-failed')[0].actionability, 'needs-review');
  assert.deepEqual(byRule('osv-lookup-failed')[0].dependencyPath.map(step => step.label), ['Web App', 'vulnerable-lib@1.0.2', 'flaky-lib@0.9.0']);
  assert.equal(byRule('osv-unqueried').length, 1, 'unqueried packages aggregate per project');
  assert.match(byRule('osv-unqueried')[0].title, /1 npm package version in Web App/);
  assert.equal(byRule('unsupported-ecosystem')[0].artifact.ecosystem, 'PyPI');
  assert.deepEqual(byRule('coverage-gap')[0].v1Ids, ['missing-lock:unlocked-tool']);
  assert.equal(byRule('npm-deprecation')[0].actionability, 'actionable');
  assert.equal(byRule('npm-deprecation-cached')[0].artifact.name, 'legacy-helper');
  assert.equal(byRule('npm-deprecation-cached')[0].coverageState, 'unqueried');
  assert.equal(byRule('newer-latest')[0].actionability, 'informational');
  assert.equal(byRule('newer-latest')[0].latestTag, '2.4.0');
  assert.equal(byRule('unpinned-action')[0].severitySource, 'policy');
  assert.equal(byRule('stale-scan').length, 0);
  assert.equal(first.gate.status, 'not-configured');
  assert.ok(first.findings.every(finding => ['actionable', 'needs-review', 'informational'].includes(finding.actionability)), 'no finding can be labelled safe or resolved');
  const text = JSON.stringify(first);
  assert.ok(!text.includes('/portfolio/'), 'absolute roots never enter the policy result');
  assert.ok(!text.includes(AT.slice(0, 10) + 'T00:00:00.000Z"') || text.indexOf(AT) === text.lastIndexOf(AT), 'evaluation time appears once, not inside identities');
  const later = evaluate(snapshot, policy, { now: '2026-11-30T00:00:00.000Z' });
  assert.equal(later.freshness.state, 'stale');
  assert.equal(later.findings.filter(finding => finding.ruleId === 'stale-scan').length, 1);
  assert.equal(later.checks.artifacts.find(record => record.name === 'vulnerable-lib').osv, 'stale');
  assert.deepEqual(later.findings.filter(f => f.ruleId !== 'stale-scan').map(f => f.id).sort(), first.findings.map(f => f.id).sort(), 'identities do not depend on evaluation time');
  const gated = evaluate(snapshot, { ...policy, gate: { failOn: ['actionable'] } }, { now: AT });
  assert.equal(gated.status, undefined);
  assert.equal(gated.gate.status, 'fail');
  assert.ok(gated.gate.failing.includes(advisory.id));
  const severityGate = evaluate(snapshot, { ...policy, gate: { failOn: ['CRITICAL'] } }, { now: AT });
  assert.equal(severityGate.gate.status, 'pass');
});

test('finding identity excludes paths and timestamps; a failed later check leaves a finding unknown, not resolved', async () => {
  const snapshot = await readJson('contracts/examples/enriched-snapshot.json');
  const policy = await readJson('contracts/policy.default.json');
  const moved = JSON.parse(JSON.stringify(snapshot));
  moved.generatedAt = '2026-10-30T18:00:00.000Z';
  for (const node of moved.nodes) if (node.rootPath) node.rootPath = node.rootPath.replace('/portfolio/', 'C:\\Users\\someone\\code\\');
  const a = evaluate(snapshot, policy, { now: AT }), b = evaluate(moved, policy, { now: AT });
  assert.deepEqual(a.findings.map(f => f.id), b.findings.map(f => f.id));
  assert.equal(findingIdentity(['osv-advisory', 'GHSA-1', 'npm', 'npm:a@1.0.0', 'p', 'node_modules/a']), findingIdentity(['osv-advisory', 'GHSA-1', 'npm', 'npm:a@1.0.0', 'p', 'node_modules/a']));
  assert.notEqual(eventIdentity('f_1', 'observed', '1.0.0'), eventIdentity('f_1', 'observed', '1.0.1'));

  const previous = a;
  const failedLater = JSON.parse(JSON.stringify(snapshot));
  failedLater.generatedAt = '2026-10-31T06:00:00.000Z';
  failedLater.enrichment.packages['npm:vulnerable-lib@1.0.2'].osv = { status: 'error', checkedAt: '2026-10-31T06:05:00.000Z', reason: 'HTTP 503' };
  const unknown = evaluate(failedLater, policy, { now: '2026-10-31T07:00:00.000Z', previous });
  const advisoryId = previous.findings.find(f => f.ruleId === 'osv-advisory').id;
  const transition = unknown.transitions.find(t => t.findingId === advisoryId);
  assert.equal(transition.transition, 'unknown');
  assert.match(transition.reason, /No comparable successful check/);
  assert.ok(unknown.transitions.some(t => t.ruleId === 'osv-lookup-failed' && t.transition === 'observed'));

  const fixedLater = JSON.parse(JSON.stringify(snapshot));
  fixedLater.generatedAt = '2026-10-31T06:00:00.000Z';
  fixedLater.enrichment.packages['npm:vulnerable-lib@1.0.2'].osv = { status: 'checked', checkedAt: '2026-10-31T06:05:00.000Z', advisories: [] };
  const resolved = evaluate(fixedLater, policy, { now: '2026-10-31T07:00:00.000Z', previous });
  assert.equal(resolved.transitions.find(t => t.findingId === advisoryId).transition, 'no-longer-observed');
  const again = evaluate(fixedLater, policy, { now: '2026-10-31T07:00:00.000Z', previous });
  assert.deepEqual(resolved.transitions, again.transitions, 'retries produce identical event keys');
  const still = evaluate(snapshot, policy, { now: AT, previous });
  assert.ok(still.transitions.every(t => t.transition === 'still-observed'));
  assert.deepEqual(validate(await loadSchema('policy-result'), resolved).errors, []);
});

test('the CLI evaluates, self-validates, and exits 3 only on a configured gate failure', async () => {
  const dir = resolve(scratch, 'cli'); await mkdir(dir, { recursive: true });
  const out = resolve(dir, 'result.json');
  const plain = spawnSync(process.execPath, [cli, 'evaluate', '--snapshot', resolve(base, 'contracts/examples/enriched-snapshot.json'), '--policy', resolve(base, 'contracts/policy.default.json'), '--at', AT, '--out', out], { encoding: 'utf8' });
  assert.equal(plain.status, 0, plain.stderr);
  assert.match(plain.stderr, /gate not-configured/);
  assert.deepEqual(JSON.parse(await readFile(out, 'utf8')), await readJson('contracts/examples/policy-result.json'));
  const gatePolicy = resolve(dir, 'gate.json');
  await writeFile(gatePolicy, JSON.stringify({ ...(await readJson('contracts/policy.default.json')), id: 'gate', gate: { failOn: ['actionable'] } }));
  const gated = spawnSync(process.execPath, [cli, 'evaluate', '--snapshot', resolve(base, 'contracts/examples/enriched-snapshot.json'), '--policy', gatePolicy, '--at', AT, '--out', '-'], { encoding: 'utf8' });
  assert.equal(gated.status, 3);
  assert.match(gated.stderr, /Gate failed/);
  assert.equal(JSON.parse(gated.stdout).gate.status, 'fail');
});
